#!/usr/bin/env python3
"""Draw the site's app icon: web/icons/icon.svg, icon-192.png and icon-512.png.

The mark is original (no game art): a green rounded square with a dark letter A whose peak grows
a two-leaf sprout. It is made only of simple shapes (round-ended thick lines and leaf outlines from
two curves), described once below in a 512 x 512 grid, then written as SVG text and drawn as PNGs
with Pillow. Pillow draws at 4x size and scales down for smooth edges; no SVG renderer is needed.

Running it again gives byte-identical files and leaves unchanged files alone.

Usage (from the repository root):
  python scripts/make_icons.py            write the icons; prints what changed
  python scripts/make_icons.py --check    write nothing; exit 1 if a file is missing or out of date
"""

import argparse
import io
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "icons"

GRID = 512
CORNER = 112  # rounded-square corner radius
BACKGROUND = "#6cc5a4"  # --accent in web/style.css (dark theme)
INK = "#0e1013"  # --bg in web/style.css (dark theme)

# Thick round-ended lines: (start, end, width). Together they make the A and the sprout's stem.
STROKES = [
    ((148, 412), (256, 214), 52),  # left leg of the A
    ((256, 214), (364, 412), 52),  # right leg
    ((190, 334), (322, 334), 44),  # crossbar
    ((256, 214), (256, 150), 26),  # stem
]
# Leaves: (base, tip, bulge). Each is two quadratic curves from base to tip whose control points
# sit `bulge` either side of the base-tip midpoint.
LEAVES = [
    ((256, 170), (170, 116), 58),
    ((256, 156), (350, 96), 62),
]


def leaf_controls(base, tip, bulge):
    """The two control points of a leaf's outline curves."""
    (bx, by), (tx, ty) = base, tip
    mx, my = (bx + tx) / 2, (by + ty) / 2
    length = math.hypot(tx - bx, ty - by)
    nx, ny = -(ty - by) / length, (tx - bx) / length
    return (mx + nx * bulge, my + ny * bulge), (mx - nx * bulge, my - ny * bulge)


def fmt(value):
    """A number for the SVG text: at most one decimal, no trailing zeros."""
    text = f"{value:.1f}".rstrip("0").rstrip(".")
    return "0" if text == "-0" else text


def svg_text():
    lines = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">',
        "  <!-- Aniimax (personal fork) app icon. Generated by scripts/make_icons.py; edit that, not this. -->",
        f'  <rect width="{GRID}" height="{GRID}" rx="{CORNER}" fill="{BACKGROUND}"/>',
        f'  <g fill="none" stroke="{INK}" stroke-linecap="round" stroke-linejoin="round">',
    ]
    for (x1, y1), (x2, y2), width in STROKES:
        lines.append(f'    <line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke-width="{width}"/>')
    lines.append("  </g>")
    lines.append(f'  <g fill="{INK}">')
    for base, tip, bulge in LEAVES:
        c1, c2 = leaf_controls(base, tip, bulge)
        d = (
            f"M{fmt(base[0])} {fmt(base[1])}"
            f"Q{fmt(c1[0])} {fmt(c1[1])} {fmt(tip[0])} {fmt(tip[1])}"
            f"Q{fmt(c2[0])} {fmt(c2[1])} {fmt(base[0])} {fmt(base[1])}Z"
        )
        lines.append(f'    <path d="{d}"/>')
    lines.append("  </g>")
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def quadratic(p0, p1, p2, steps=48):
    """Points along a quadratic curve from p0 to p2 with control point p1."""
    points = []
    for i in range(steps + 1):
        t = i / steps
        a, b, c = (1 - t) ** 2, 2 * (1 - t) * t, t * t
        points.append((a * p0[0] + b * p1[0] + c * p2[0], a * p0[1] + b * p1[1] + c * p2[1]))
    return points


def draw_png(size):
    scale = size * 4 / GRID
    big = size * 4

    def s(point):
        return (point[0] * scale, point[1] * scale)

    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((0, 0, big - 1, big - 1), radius=CORNER * scale, fill=BACKGROUND)
    for start, end, width in STROKES:
        # A round-ended thick line is a rectangle plus a disc at each end.
        (x1, y1), (x2, y2) = s(start), s(end)
        half = width * scale / 2
        length = math.hypot(x2 - x1, y2 - y1)
        nx, ny = -(y2 - y1) / length * half, (x2 - x1) / length * half
        draw.polygon([(x1 + nx, y1 + ny), (x2 + nx, y2 + ny), (x2 - nx, y2 - ny), (x1 - nx, y1 - ny)], fill=INK)
        for cx, cy in ((x1, y1), (x2, y2)):
            draw.ellipse((cx - half, cy - half, cx + half, cy + half), fill=INK)
    for base, tip, bulge in LEAVES:
        c1, c2 = leaf_controls(base, tip, bulge)
        outline = quadratic(base, c1, tip) + quadratic(tip, c2, base)[1:]
        draw.polygon([s(p) for p in outline], fill=INK)
    small = image.resize((size, size), Image.Resampling.LANCZOS)
    buffer = io.BytesIO()
    small.save(buffer, format="PNG", optimize=True)
    return buffer.getvalue()


def outputs():
    return {
        OUT / "icon.svg": svg_text().encode("utf-8"),
        OUT / "icon-192.png": draw_png(192),
        OUT / "icon-512.png": draw_png(512),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if out of date")
    args = parser.parse_args(argv)

    stale = []
    for path, data in outputs().items():
        name = path.relative_to(ROOT).as_posix()
        if path.exists() and path.read_bytes() == data:
            print(f"unchanged  {name}")
            continue
        stale.append(name)
        if args.check:
            print(f"OUT OF DATE  {name}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"wrote      {name} ({len(data)} bytes)")
    return 1 if args.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
